import React, { useState } from 'react';
import { sampleReports } from '../data/mockNemsData';
import { MarketReport } from '../types/nems';
import { X, Download, FileText, Check, Calendar } from 'lucide-react';

interface TradingReportsModalProps {
  isOpen: boolean;
  onClose: () => void;
}

export const TradingReportsModal: React.FC<TradingReportsModalProps> = ({
  isOpen,
  onClose,
}) => {
  const [downloadingId, setDownloadingId] = useState<string | null>(null);
  const [downloadedId, setDownloadedId] = useState<string | null>(null);
  const [selectedFilter, setSelectedFilter] = useState<'All' | 'Daily' | 'Weekly' | 'Monthly' | 'Quarterly'>('All');

  if (!isOpen) return null;

  const filteredReports =
    selectedFilter === 'All'
      ? sampleReports
      : sampleReports.filter((r) => r.category === selectedFilter);

  const handleDownload = (report: MarketReport) => {
    setDownloadingId(report.id);
    setTimeout(() => {
      // Mock synthetic file download
      const content = `Energy Market Company (EMC) - National Electricity Market of Singapore\nReport: ${report.title}\nCategory: ${report.category}\nDate: ${report.date}\n\nKey Highlights:\n- Peak Demand: 7,560 MW\n- Average USEP: $184.20 / MWh\n- Peak Solar Generation: 1,507 MW (Settlement Period 25)\n- Reserve Margin Compliance: 30.5%\n- MEUC Estimate: $0.85 / MWh\n\nOfficial settlement report generated by EMC Operations.`;
      const blob = new Blob([content], { type: report.type === 'CSV' ? 'text/csv' : 'text/plain' });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = `${report.title.replace(/[^a-zA-Z0-9]/g, '_')}.${report.type.toLowerCase()}`;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(url);

      setDownloadingId(null);
      setDownloadedId(report.id);
      setTimeout(() => setDownloadedId(null), 3000);
    }, 500);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/50 backdrop-blur-xs">
      <div className="bg-white rounded-lg shadow-xl w-full max-w-2xl overflow-hidden border border-gray-200">
        {/* Modal Header */}
        <div className="px-6 py-4 border-b border-gray-200 flex items-center justify-between bg-gray-50">
          <div className="flex items-center gap-2">
            <FileText className="w-5 h-5 text-[#0055b8]" />
            <h3 className="text-base font-bold text-gray-900">NEMS Market Trading Reports</h3>
          </div>
          <button
            onClick={onClose}
            className="text-gray-400 hover:text-gray-600 p-1 rounded-full hover:bg-gray-200 transition-colors cursor-pointer"
            aria-label="Close"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Filter Pills */}
        <div className="px-6 py-3 border-b border-gray-100 flex items-center gap-2 overflow-x-auto text-xs">
          {(['All', 'Daily', 'Weekly', 'Monthly', 'Quarterly'] as const).map((cat) => (
            <button
              key={cat}
              onClick={() => setSelectedFilter(cat)}
              className={`px-3 py-1 font-medium rounded transition-colors cursor-pointer ${
                selectedFilter === cat
                  ? 'bg-[#0055b8] text-white'
                  : 'bg-gray-100 text-gray-600 hover:bg-gray-200'
              }`}
            >
              {cat}
            </button>
          ))}
        </div>

        {/* Reports List */}
        <div className="px-6 py-4 max-h-[60vh] overflow-y-auto space-y-3">
          {filteredReports.map((report) => (
            <div
              key={report.id}
              className="border border-gray-200 rounded p-3.5 hover:border-blue-300 hover:bg-blue-50/20 transition-colors flex flex-col sm:flex-row sm:items-center justify-between gap-3"
            >
              <div className="space-y-1">
                <div className="flex items-center gap-2">
                  <span className="text-[10px] font-semibold uppercase px-1.5 py-0.5 rounded bg-blue-100 text-blue-800">
                    {report.category}
                  </span>
                  <span className="text-[10px] font-mono text-gray-500">{report.type} · {report.fileSize}</span>
                </div>
                <h4 className="text-xs font-semibold text-gray-900">{report.title}</h4>
                <p className="text-[11px] text-gray-600 leading-snug">{report.description}</p>
                <div className="flex items-center gap-1 text-[10px] text-gray-400">
                  <Calendar className="w-3 h-3" />
                  <span>Published {report.date}</span>
                </div>
              </div>

              <button
                onClick={() => handleDownload(report)}
                disabled={downloadingId === report.id}
                className="shrink-0 flex items-center justify-center gap-1.5 px-3 py-1.5 text-xs font-semibold text-[#0055b8] border border-[#0055b8] hover:bg-[#0055b8] hover:text-white rounded transition-colors cursor-pointer"
              >
                {downloadedId === report.id ? (
                  <>
                    <Check className="w-3.5 h-3.5 text-emerald-600" />
                    <span>Saved</span>
                  </>
                ) : (
                  <>
                    <Download className="w-3.5 h-3.5" />
                    <span>{downloadingId === report.id ? 'Loading...' : 'Download'}</span>
                  </>
                )}
              </button>
            </div>
          ))}
        </div>

        {/* Footer */}
        <div className="px-6 py-3 bg-gray-50 border-t border-gray-200 flex justify-between items-center text-xs text-gray-500">
          <span>Need specialized market analytics? Contact our subscription desk.</span>
          <button
            onClick={onClose}
            className="px-4 py-1.5 bg-gray-200 hover:bg-gray-300 text-gray-800 rounded font-medium transition-colors cursor-pointer"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
};
